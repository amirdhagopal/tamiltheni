def main():
    with open("src/data/theni5_words.json", "r", encoding="utf-8") as f:
        words = json.load(f)

    # Build deduplicated tie-breaker list
    seen = set()
    tb_words = []
    for key, word_str in TB.items():
        for w in word_str.split(","):
            w = w.strip()
            if w and w not in seen:
                seen.add(w)
                tb_words.append({"w": w, "c": [C[key]]})

    # Assign serial numbers
    for i, entry in enumerate(tb_words, 1):
        entry["s"] = i
        entry["y"] = "Tie Breaker"

    # Append to existing words
    words.extend(tb_words)

    with open("src/data/theni5_words.json", "w", encoding="utf-8") as f:
        json.dump(words, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Added {len(tb_words)} tie-breaker words")
    print(f"Total words now: {len(words)}")

    from collections import Counter
    cc = Counter()
    for w in tb_words:
        for c in w["c"]:
            cc[c] += 1
    print("\nTie-breaker category distribution:")
    for cat, count in cc.most_common():
        print(f"  {cat}: {count}")

if __name__ == "__main__":
    main()
